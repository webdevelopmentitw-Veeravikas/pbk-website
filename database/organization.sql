-- Organization Teams & Members
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `organization_teams` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(200) NOT NULL,
  `slug` VARCHAR(220) NOT NULL,
  `description` LONGTEXT DEFAULT NULL,
  `banner` VARCHAR(255) DEFAULT NULL,
  `image` VARCHAR(255) DEFAULT NULL,
  `sort_order` INT NOT NULL DEFAULT 0,
  `status` TINYINT(1) NOT NULL DEFAULT 1,
  `seo_title` VARCHAR(255) DEFAULT NULL,
  `seo_description` TEXT DEFAULT NULL,
  `seo_keywords` VARCHAR(255) DEFAULT NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `org_teams_slug_unique` (`slug`),
  KEY `org_teams_status_sort` (`status`, `sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `organization_members` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `team_id` INT UNSIGNED NOT NULL,
  `name` VARCHAR(200) NOT NULL,
  `tamil_name` VARCHAR(200) DEFAULT NULL,
  `english_name` VARCHAR(200) DEFAULT NULL,
  `photo` VARCHAR(255) DEFAULT NULL,
  `cover_image` VARCHAR(255) DEFAULT NULL,
  `designation` VARCHAR(200) DEFAULT NULL,
  `position` VARCHAR(200) DEFAULT NULL,
  `assembly` VARCHAR(150) DEFAULT NULL,
  `parliament` VARCHAR(150) DEFAULT NULL,
  `district` VARCHAR(150) DEFAULT NULL,
  `address` TEXT DEFAULT NULL,
  `state` VARCHAR(100) DEFAULT 'தமிழ்நாடு',
  `zone` VARCHAR(100) DEFAULT NULL,
  `phone` VARCHAR(40) DEFAULT NULL,
  `email` VARCHAR(190) DEFAULT NULL,
  `whatsapp` VARCHAR(40) DEFAULT NULL,
  `facebook` VARCHAR(255) DEFAULT NULL,
  `twitter` VARCHAR(255) DEFAULT NULL,
  `instagram` VARCHAR(255) DEFAULT NULL,
  `youtube` VARCHAR(255) DEFAULT NULL,
  `website` VARCHAR(255) DEFAULT NULL,
  `biography` LONGTEXT DEFAULT NULL,
  `joining_date` DATE DEFAULT NULL,
  `sort_order` INT NOT NULL DEFAULT 0,
  `featured` TINYINT(1) NOT NULL DEFAULT 0,
  `status` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `org_members_team_id` (`team_id`),
  KEY `org_members_status_sort` (`status`, `sort_order`),
  KEY `org_members_district` (`district`),
  KEY `org_members_assembly` (`assembly`),
  KEY `org_members_featured` (`featured`),
  FULLTEXT KEY `org_members_search` (`name`, `tamil_name`, `english_name`, `designation`, `position`, `district`, `assembly`),
  CONSTRAINT `org_members_team_fk` FOREIGN KEY (`team_id`) REFERENCES `organization_teams` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
